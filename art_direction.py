def choose_art_direction(seed: str) -> dict:
    digest = sha256(seed.encode("utf-8")).digest()
    return DIRECTIONS[int.from_bytes(digest[:2], "big") % len(DIRECTIONS)]


def art_direction_prompt(seed: str) -> str:
    direction = choose_art_direction(seed)
    return (
        "\n\nВЫБРАННАЯ АРТ-ДИРЕКЦИОННАЯ ШКОЛА (адаптируй к брифу, не копируй шаблон):\n"
        f"Направление: {direction['name']}\n"
        f"Принцип: {direction['brief']}\n"
        f"Избегай: {direction['avoid']}\n"
        "Это только творческая оптика. Сам выбери конкретную композицию, палитру и структуру под продукт; "
        "не называй направление пользователю и не повторяй его буквально между сайтами."
    )
